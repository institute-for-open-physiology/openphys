#!/usr/bin/env python3
"""Generate native design values and screen names. --check rejects drift."""

import argparse
import json
import re
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ANDROID = ROOT / "android/app/src/main/java/com/vineyardfinance/sensors/ui"
IOS = ROOT / "ios/TrainingSensors"


def quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def generate() -> tuple[dict[Path, str], list[tuple[str, dict[str, typing.Any]]]]:
    tokens = json.loads((ROOT / "shared/design/tokens.json").read_text())
    screens = []
    for path in (ROOT / "shared/screens").glob("*.json"):
        assert re.fullmatch(r"[A-Z][A-Za-z0-9]*", path.stem), path
        screens.append((path.stem, json.loads(path.read_text())))
    screens.sort(key=lambda pair: pair[1]["order"])
    assert len({data["order"] for _, data in screens}) == len(screens)
    swift = [
        "// Generated by scripts/mobile_contract.py. Edit shared/ instead.",
        "import SwiftUI",
        "import UIKit",
        "",
        "enum Palette {",
    ]
    kotlin = [
        "// Generated by scripts/mobile_contract.py. Edit shared/ instead.",
        "package com.vineyardfinance.sensors.ui",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "data class MobileColors(",
    ]
    for name in tokens["colors"]:
        kotlin.append(f"    val {name}: Color,")
    kotlin += [")", "", "fun mobileColors(dark: Boolean) = MobileColors("]
    for name, modes in tokens["colors"].items():
        for value in modes.values():
            assert re.fullmatch(r"#[0-9a-f]{6}", value), value
        light, dark = modes["light"][1:], modes["dark"][1:]
        swift.append(f"    static let {name} = dynamic(0x{light}, 0x{dark})")
        kotlin.append(f"    {name} = Color(if (dark) 0xff{dark} else 0xff{light}),")
    kotlin += [")", "", "object Layout {"]
    swift += [
        "",
        "    private static func dynamic(_ light: UInt32, _ dark: UInt32) -> Color {",
        "        Color(UIColor { style in",
        "            let hex = style.userInterfaceStyle == .dark ? dark : light",
        "            return UIColor(red: CGFloat((hex >> 16) & 255) / 255, green: CGFloat((hex >> 8) & 255) / 255, blue: CGFloat(hex & 255) / 255, alpha: 1)",
        "        })",
        "    }",
        "}",
        "",
        "enum Layout {",
    ]
    for name, value in tokens["dimensions"].items():
        assert isinstance(value, (int, float)) and value > 0
        swift.append(f"    static let {name}: CGFloat = {value}")
        kotlin.append(f"    const val {name} = {value}")
    swift += ["}", "", "enum MobileScreen: Int, CaseIterable {"]
    swift += [
        "    case " + ", ".join(name[0].lower() + name[1:] for name, _ in screens)
    ]
    swift += ["    var title: String {", "        switch self {"]
    for name, data in screens:
        swift.append(
            f"        case .{name[0].lower() + name[1:]}: {quote(data['title'])}"
        )
    swift += ["        }", "    }", "}"]
    kotlin += ["}", "", "enum class MobileScreen(val title: String) {"]
    kotlin += [f"    {name}({quote(data['title'])})," for name, data in screens]
    kotlin += [
        "}",
        "",
        'data class Section(val title: String, val info: String? = null, val unit: String = "")',
    ]
    swift += [
        "",
        "struct Section { let title: String; let info: String?; let unit: String }",
    ]
    for name, data in screens:
        kotlin += ["", f"object {name}Content {{"]
        swift += ["", f"enum {name}Content {{"]
        for key, section in data["sections"].items():
            title, info, unit = (
                quote(section["title"]),
                quote(section["info"]) if "info" in section else None,
                quote(section.get("unit", "")),
            )
            swift.append(
                f"    static let {key} = Section(title: {title}, info: {info or 'nil'}, unit: {unit})"
            )
            kotlin.append(f"    val {key} = Section({title}, {info or 'null'}, {unit})")
        swift += ["}"]
        kotlin += ["}"]
    files = {}
    resources = ROOT / "android/app/src/main/res"
    for mode, folder in [("light", "values"), ("dark", "values-night")]:
        lines = [
            "<!-- Generated by scripts/mobile_contract.py. Edit shared/ instead. -->",
            "<resources>",
        ]
        lines += [
            f'    <color name="{name}">{values[mode]}</color>'
            for name, values in tokens["colors"].items()
        ]
        lines += ["</resources>"]
        files[resources / folder / "colors.xml"] = "\n".join(lines) + "\n"
    return {
        **files,
        IOS / "MobileDesign.swift": "\n".join(swift) + "\n",
        ANDROID / "MobileDesign.kt": "\n".join(kotlin) + "\n",
    }, screens


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, screens = generate()
    errors = []
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                errors.append(f"Stale output: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check:
        for name, _ in screens:
            for directory, suffix, declaration in [
                (IOS, "swift", "struct"),
                (ANDROID, "kt", "fun"),
            ]:
                path = directory / f"{name}View.{suffix}"
                if not path.exists() or not re.search(
                    rf"\b{declaration}\s+{name}View\b", path.read_text()
                ):
                    errors.append(f"Missing native screen: {path.relative_to(ROOT)}")
        if errors:
            raise SystemExit("\n".join(errors))
    print(
        f"{len(screens)} shared screens; native design values {'checked' if args.check else 'generated'}."
    )


if __name__ == "__main__":
    main()
